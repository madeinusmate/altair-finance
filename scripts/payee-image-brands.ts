export const brandKeys = (brand: PayeeBrand): string[] => {
  const keys = [brand.title, ...(brand.aliases ?? [])].map((value) => cleanPayee(value)?.normalizedName ?? "");
  return [...new Set(keys.filter((key) => key.length > 0))];
};

const startsWithKey = (haystack: string, key: string): boolean => {
  if (!haystack.startsWith(key)) return false;
  return haystack.length === key.length || SEPARATOR.test(haystack[key.length] ?? "");
};

const containsKey = (haystack: string, key: string): boolean => {
  let from = 0;
  while (from <= haystack.length - key.length) {
    const index = haystack.indexOf(key, from);
    if (index < 0) return false;
    const beforeOk = index === 0 || SEPARATOR.test(haystack[index - 1] ?? "");
    const afterIndex = index + key.length;
    const afterOk = afterIndex === haystack.length || SEPARATOR.test(haystack[afterIndex] ?? "");
    if (beforeOk && afterOk) return true;
    from = index + 1;
  }
  return false;
};

const keyFolds = (brand: PayeeBrand, key: string): boolean => {
  if (brand.fold === false || FOLD_OFF.has(key)) return false;
  if (brand.fold === true) return true;
  return key.length >= 4;
};

export type BrandMatch = { brand: PayeeBrand; key: string };

// Longest key wins so "Amazon Prime" beats "Amazon" and "Uber Eats" is not swallowed by "Uber".
export const matchPayeeBrand = (name: string, brands: PayeeBrand[] = PAYEE_BRANDS): BrandMatch | null => {
  const normalized = cleanPayee(name)?.normalizedName;
  if (!normalized) return null;
  let best: BrandMatch | null = null;
  for (const brand of brands) {
    for (const key of brandKeys(brand)) {
      const fold = keyFolds(brand, key);
      const matched = normalized === key || (fold && (startsWithKey(normalized, key) || (key.length >= 6 && containsKey(normalized, key))));
      if (!matched) continue;
      if (!best || key.length > best.key.length) best = { brand, key };
    }
  }
  return best;
};
